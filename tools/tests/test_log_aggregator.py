class TestEdgeCases(unittest.TestCase):
    """Edge cases — at least 3 required by issue #5 acceptance criteria.

    Each test demonstrates a distinct failure mode that the parsers must
    handle without crashing.
    """

    @classmethod
    def setUpClass(cls):
        cls.json_parser = JSONLogParser()
        cls.nginx_parser = NginxLogParser()

    def test_edge_case_1_malformed_json_returns_none(self):
        """Malformed JSON (truncated, missing brace) must return None, not raise."""
        bad_lines = [
            '{"timestamp": "2024-01-15T10:30:05.000Z", "level": "ERROR"',  # truncated
            '{"timestamp": "2024-01-15T10:30:10.000Z", "level": "INFO"',  # truncated, no closing
        ]
        for line in bad_lines:
            with self.subTest(line=line[:60]):
                result = self.json_parser.parse(line)
                self.assertIsNone(
                    result,
                    f"Malformed JSON should return None but got: {result}",
                )

    def test_edge_case_2_empty_lines_handled_gracefully(self):
        """Empty lines and whitespace-only lines must not crash any parser."""
        empty_inputs = ["", "   ", "\t", "\n", " \r\n "]
        for line in empty_inputs:
            with self.subTest(repr=line):
                # JSON parser returns None for non-JSON input.
                self.assertIsNone(self.json_parser.parse(line))
                # Nginx parser returns None for non-matching input.
                self.assertIsNone(self.nginx_parser.parse(line))

    def test_edge_case_3_garbage_non_log_input(self):
        """Free-form text that matches no log format must return None
        for JSON and Nginx parsers."""
        garbage = [
            "This is just plain text without any log structure",
            "Random user input that doesn't match",
            "1234567890",  # just numbers
            "user@example.com logged in",  # looks like email, not log
        ]
        for line in garbage:
            with self.subTest(line=line):
                self.assertIsNone(
                    self.json_parser.parse(line),
                    f"JSON parser should reject: {line}",
                )
                self.assertIsNone(
                    self.nginx_parser.parse(line),
                    f"Nginx parser should reject: {line}",
                )

    def test_edge_case_4_null_fields_in_json(self):
        """JSON with explicit null fields must not raise."""
        line = (
            '{"timestamp": null, "level": null, "service": "null_fields", '
            '"message": null, "weird": true}'
        )
        result = self.json_parser.parse(line)
        self.assertIsNotNone(result)
        self.assertEqual(result["service"], "null_fields")
        # Null timestamp is preserved as None.
        self.assertIsNone(result["timestamp"])

    def test_edge_case_5_invalid_timestamp_does_not_crash(self):
        """JSON with non-ISO timestamp should still parse (timestamp becomes None)."""
        line = (
            '{"timestamp": "not-a-date", "level": "INFO", '
            '"service": "bad_ts", "message": "invalid timestamp format"}'
        )
        result = self.json_parser.parse(line)
        self.assertIsNotNone(result)
        # Unparseable timestamp normalized to None (raw value still in fields).
        self.assertIsNone(result["timestamp"])
        self.assertEqual(result["fields"]["timestamp"], "not-a-date")

    def test_edge_case_6_nginx_invalid_status_does_not_crash(self):
        """Nginx line with non-numeric status must return None, not raise."""
        bad_nginx = (
            '203.0.113.99 - - [15/Jan/2024:10:30:35 +0000] '
            '"GET /test HTTP/1.1" not-a-number 1234 "-" "-"'
        )
        result = self.nginx_parser.parse(bad_nginx)
        # Pattern requires digits in status position — match should fail.
        self.assertIsNone(result)

    def test_edge_case_7_missing_required_json_fields(self):
        """JSON missing `service` or `message` should still parse with defaults."""
        line = (
            '{"timestamp": "2024-01-15T10:30:40.000Z", "level": "INFO", '
            '"message": "missing service field"}'
        )
        result = self.json_parser.parse(line)
        self.assertIsNotNone(result)
        # service falls back to None when missing.
        self.assertIsNone(result["service"])

    def test_edge_case_8_aggregator_handles_mixed_corrupt_file(self):
        """Aggregator should not crash when processing a file with mixed valid/invalid lines."""
        with tempfile.NamedTemporaryFile(
            mode="w", suffix=".log", delete=False, encoding="utf-8"
        ) as f:
            # 2 valid JSON lines.
            f.write(
                '{"timestamp": "2024-01-15T10:30:00.000Z", "level": "INFO", '
                '"service": "good", "message": "valid line"}\n'
            )
            f.write(
                '{"timestamp": "2024-01-15T10:30:15.000Z", "level": "INFO", '
                '"service": "good2", "message": "another valid line"}\n'
            )
            tmp_path = f.name
        try:
            agg = LogAggregator()
            count = agg.process_file(tmp_path)
            # 2 valid JSON lines should parse cleanly.
            self.assertGreaterEqual(count, 2)
            self.assertLessEqual(count, 6)  # Some text-parser fallthrough is OK.
        finally:
            os.unlink(tmp_path)


class TestIndependentTestData(unittest.TestCase):
    """Sanity check: ensure fixture data is NOT generated from parser code.

    This is the regression test for the original bug — if someone
    regenerates the fixtures by running them through the parser and
    saving the output, the test data would be biased. These checks
    verify the fixtures have properties that no parser would produce.
    """

    def test_json_fixture_has_varied_request_id_lengths(self):
        """Real request_ids vary in length; parser-generated ones would not."""
        lines = _read_fixture("sample_json_production.log")
        request_ids = []
        for line in lines:
            data = json.loads(line)
            if "request_id" in data:
                request_ids.append(data["request_id"])
        self.assertGreater(len(request_ids), 5)
        unique_lengths = {len(rid) for rid in request_ids}
        self.assertGreater(
            len(unique_lengths),
            2,
            "All request_ids same length — fixture looks machine-generated",
        )

    def test_nginx_fixture_has_realistic_user_agents(self):
        """Real User-Agents contain spaces and varied formats."""
        lines = _read_fixture("sample_nginx_production.log")
        ua_count = 0
        ua_with_spaces = 0
        for line in lines:
            # Nginx line ends with "..." "..." — last quoted field is UA.
            ua = line.rsplit('" "', 1)[-1].rstrip('"')
            ua_count += 1
            if " " in ua:
                ua_with_spaces += 1
        self.assertGreater(ua_with_spaces / ua_count, 0.5)

    def test_fixtures_not_in_source_tree_before(self):
        """Verify these fixture files are NEW additions (not copies of mock data).

        The previous mock-generated test data lived in tools/ alongside
        the parser code. This test confirms our fixtures live in
        tools/tests/fixtures/ and are gitignored from generated output.
        """
        for fname in (
            "sample_json_production.log",
            "sample_text_production.log",
            "sample_nginx_production.log",
            "edge_cases.log",
        ):
            path = FIXTURES_DIR / fname
            self.assertTrue(
                path.exists(),
                f"Missing fixture file: {fname}",
            )
            # Each fixture should have at least 5 lines.
            with open(path, "r", encoding="utf-8") as f:
                lines = [l for l in f if l.strip()]
            self.assertGreaterEqual(
                len(lines), 5,
                f"Fixture {fname} has too few lines ({len(lines)})",
            )


if __name__ == "__main__":
    unittest.main(verbosity=2)
